export function randomFromList(list) {
    const index = Math.floor(Math.random() * list.length);
    return list[index];
}

const currentCharacter = [];
const savedList = [];

// ป้องกันการสุ่มธีมหลักหรือธีมรองซ้ำกัน
function randomTheme() {
    const usedThemes = currentCharacter
        .filter(item =>
            item.startsWith("ธีมหลัก: ") ||
            item.startsWith("ธีมรอง: ")
        )
        .map(item => item.substring(item.indexOf(": ") + 2));

    const availableThemes = theme_list.filter(
        theme => !usedThemes.includes(theme)
    );

    // หากธีมถูกใช้ครบทั้งหมดแล้ว ให้เริ่มสุ่มซ้ำได้
    return randomFromList(
        availableThemes.length > 0 ? availableThemes : theme_list
    );
}

export function generateRandomCharacter() {
    const step = currentCharacter.length;

    // ครบทุกหัวข้อแล้ว: กดเพิ่มเพื่อสุ่มธีมรองใหม่
    if (step >= all_lists.length) {
        currentCharacter.push(`ธีมรอง: ${randomTheme()}`);
        return;
    }

    // สุ่มตามลำดับที่กำหนด
    if (step === 0) {
        currentCharacter.push(`ธีมหลัก: ${randomTheme()}`);
        return;
    }

    if (step === 1 || step === 2) {
        currentCharacter.push(`ธีมรอง: ${randomTheme()}`);
        return;
    }

    const labels = [
        "ธีมหลัก",
        "ธีมรอง",
        "ธีมรอง",
        "แนวเสื้อผ้า",
        "สไตล์การแต่งตัว",
        "โทนสี",
        "ทรงผม",
        "อาวุธ",
        "ของตกแต่ง"
    ];

    const result = randomFromList(all_lists[step]);
    currentCharacter.push(`${labels[step]}: ${result}`);
}

export function getCurrentCharacter() {
    return currentCharacter;
}

export function saveCurrentCharacter() {
    savedList.push([...currentCharacter]);
    currentCharacter.length = 0;
}

export function getSavedList() {
    return savedList;
}

export function clearCurrentCharacter() {
    currentCharacter.length = 0;
}