const all_lists = [
    theme_list,
    profession_list,
    personality_list,
    background_list,
    quirk_list
]


export function randomFromList(list) {
    const index = Math.floor(Math.random() * list.length);
    return list[index];
}

let currentCharacter = null;

export function generateRandomCharacter() {
    const character = [];
    for (const list of all_lists) {
        const result = randomFromList(list);
        character.push(result);
    }
    currentCharacter = character;
}

export function getCurrentCharacter() {
    return currentCharacter;
}

export function clearCurrentCharacter() {
    currentCharacter.length = 0;
}