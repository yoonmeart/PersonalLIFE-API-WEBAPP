export function randomFromList(list) {
    if (!Array.isArray(list) || list.length === 0) {
        return undefined;
    }

    const index = Math.floor(Math.random() * list.length);
    return list[index];
}

const currentCharacter = [];
const savedList = [];

// สุ่มธีมที่ยังไม่ถูกใช้ หากใช้ครบแล้วจึงอนุญาตให้ซ้ำ
function randomTheme() {
    const usedThemes = currentCharacter
        .filter(item =>
            item.startsWith("ธีมหลัก: ") ||
            item.startsWith("ธีมรอง: ")
        )
        .map(item => item.substring(item.indexOf(": ") + 2));

    const availableThemes = theme_list.filter(
        theme => !usedThemes.includes(theme)
    );

    return randomFromList(
        availableThemes.length > 0
            ? availableThemes
            : theme_list
    );
}

export function generateRandomCharacter() {
    const step = currentCharacter.length;

    // เมื่อครบ 12 ขั้นตอนแล้ว สุ่มรายละเอียดพิเศษต่อไป
    if (step >= all_lists.length) {
        const bonusLists = [
            {
                label: "จุดเด่นประจำตัว",
                list: signature_feature_list
            },
            {
                label: "เอฟเฟกต์และพลัง",
                list: effect_list
            },
            {
                label: "คู่หูหรือสัตว์ประจำตัว",
                list: companion_list
            }
        ];

        const result = randomFromList(bonusLists);

        if (result !== undefined) {
            const value = randomFromList(result.list);

            if (value !== undefined) {
                currentCharacter.push(`${result.label}: ${value}`);
            }
        }

        return;
    }

    // สุ่มธีมหลักและธีมรอง
    if (step <= 2) {
        const theme = randomTheme();
        const label = step === 0 ? "ธีมหลัก" : "ธีมรอง";

        if (theme !== undefined) {
            currentCharacter.push(`${label}: ${theme}`);
        }

        return;
    }

    // สุ่มหัวข้อที่เหลือตามลำดับ
    const result = randomFromList(all_lists[step]);

    if (result !== undefined) {
        currentCharacter.push(`${labels[step]}: ${result}`);
    }
}

export function getCurrentCharacter() {
    return currentCharacter;
}

export function saveCurrentCharacter() {
    if (currentCharacter.length === 0) {
        return;
    }

    savedList.push([...currentCharacter]);
    currentCharacter.length = 0;
}

export function getSavedList() {
    return savedList;
}

export function clearCurrentCharacter() {
    currentCharacter.length = 0;
}